// Embeds the built static site (dist/) into the Worker so a single `wrangler deploy` ships everything.
import fs from 'node:fs'
import path from 'node:path'

const TEXT = { '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.html': 'text/html; charset=utf-8', '.svg': 'image/svg+xml', '.webmanifest': 'application/manifest+json', '.json': 'application/json', '.txt': 'text/plain; charset=utf-8', '.map': 'application/json' }
const BIN = { '.png': 'image/png', '.woff2': 'font/woff2', '.ico': 'image/x-icon', '.jpg': 'image/jpeg', '.webp': 'image/webp' }

const out = {}
const walk = dir => {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name)
    if (fs.statSync(full).isDirectory()) { walk(full); continue }
    const ext = path.extname(name)
    const key = '/' + path.relative('dist', full).split(path.sep).join('/')
    if (TEXT[ext]) out[key] = { type: TEXT[ext], text: fs.readFileSync(full, 'utf8') }
    else if (BIN[ext]) out[key] = { type: BIN[ext], b64: fs.readFileSync(full).toString('base64') }
    else console.warn('skipped', key)
  }
}
walk('dist')
fs.writeFileSync('worker/assets.generated.ts', `// generated by scripts/gen-assets.mjs, do not edit\nexport const ASSETS: Record<string, { type: string; text?: string; b64?: string }> = ${JSON.stringify(out)}\n`)
console.log('embedded', Object.keys(out).length, 'files')
